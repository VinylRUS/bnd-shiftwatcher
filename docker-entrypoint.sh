#!/bin/sh
# ─────────────────────────────────────────────────────────────────────────────
# Табель — точка входа контейнера (v7, «проще некуда»).
#
# Приложение целиком лежит в /srv/tabel ВНУТРИ ОБРАЗА. Платформа bothost
# при запуске контейнера монтирует в /app исходники из Git (документация
# bothost «Кастомный Dockerfile»: «бинарники, положенные в /app, будут
# скрыты этим монтированием — кладите их вне /app»), поэтому:
#
#   • из /app мы не читаем НИ ОДНОГО файла приложения и ни секунды
#     ничего не ждём — гонки «файлы ещё копируются» исчезли вместе с /app;
#   • миграции применяет prisma/migrate.js без Prisma CLI (как в v5/v6);
#   • база выбирается так: явный DATABASE_URL → /app/data (персистентная
#     папка платформы, по рекомендации bothost: «при обновлении сохраняются
#     … данные в /app/data») → том /data (docker compose) → рядом
#     с приложением (последняя надежда, с предупреждением).
#
# Шаги: выбрать базу → применить миграции → запустить сервер.
# ─────────────────────────────────────────────────────────────────────────────
set -e
cd /srv/tabel

# ── 1. путь к базе ───────────────────────────────────────────────────────────
if [ -z "${DATABASE_URL:-}" ]; then
  if [ -d /app ] && { [ -d /app/data ] || mkdir -p /app/data 2>/dev/null; } && [ -w /app/data ]; then
    DATABASE_URL="file:/app/data/tabel.db"
    echo "[tabel] база: ${DATABASE_URL} (персистентная папка платформы)"
  elif [ -d /data ] && [ -w /data ]; then
    DATABASE_URL="file:/data/tabel.db"
    echo "[tabel] база: ${DATABASE_URL} (том /data)"
  else
    mkdir -p /srv/tabel/data
    DATABASE_URL="file:/srv/tabel/data/tabel.db"
    echo "[tabel] ВНИМАНИЕ: персистентного хранилища не нашёл — база будет в ${DATABASE_URL}" >&2
    echo "[tabel] (данные не переживут пересоздание контейнера)" >&2
  fi
  export DATABASE_URL
fi

# ── 2. миграции (идемпотентно: сколько раз ни запускай — безопасно) ──────────
echo "[tabel] применяю миграции…"
node ./prisma/migrate.js

# ── 3. сервер ────────────────────────────────────────────────────────────────
echo "[tabel] запускаю сервер на 0.0.0.0:${PORT:-3000}"
exec "$@"
